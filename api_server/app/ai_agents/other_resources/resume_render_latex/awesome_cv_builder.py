"""Build an Awesome-CV resume.tex string from Agent 4 JSON."""

from __future__ import annotations

import re
from typing import Any
from urllib.parse import urlparse

from app.ai_agents.other_resources.resume_render_latex.text_escape import escape_tex
from app.ai_agents.tools.content_diff_tool import diff_resume_content
from app.services.resume_analyzer import (
    extract_contact_info,
    extract_professional_links,
)

_DEFAULT_SECTION_ORDER = (
    "summary",
    "skills",
    "experience",
    "projects",
    "education",
    "other",
)
_NAME_WORDS = re.compile(r"[A-Za-z][A-Za-z.'\-]*")
_HEADING_LINE = re.compile(
    r"^(?:professional\s+|technical\s+|work\s+)?"
    r"(?:summary|objective|profile|skills|experience|education|projects|"
    r"certifications?|languages?|volunteer(?:ing)?)\b",
    re.IGNORECASE,
)


def build_resume_tex(
    optimizer: dict[str, Any] | None,
    *,
    resume_text: str = "",
    analyzer: dict[str, Any] | None = None,
    intent: dict[str, Any] | None = None,
    contact: dict[str, Any] | None = None,
    highlight: bool = True,
    diff: dict[str, Any] | None = None,
) -> str:
    """Return a complete Awesome-CV document from optimized_sections."""
    sections = _optimizer_sections(optimizer)
    order = _section_order(optimizer, sections)
    if highlight and diff is None:
        diff = diff_resume_content(resume_text, optimizer)
    elif not highlight:
        diff = None

    header = _header_macros(resume_text, analyzer, intent, contact)
    body_parts = [
        _render_section(key, sections, diff) for key in order
    ]
    body = "\n".join(part for part in body_parts if part)

    highlight_preamble = ""
    if highlight:
        highlight_preamble = """
\\usepackage{luacolor}
\\usepackage{lua-ul}
\\LuaULSetHighLightColor{yellow!70}
"""

    footer_name = " ".join(
        part for part in (header["first_name"], header["last_name"]) if part
    ) or "Resume"

    return f"""% Generated by JobGenius Agent 5. Do not edit by hand.
\\documentclass[11pt, letterpaper]{{awesome-cv}}
\\geometry{{left=1.4cm, top=.8cm, right=1.4cm, bottom=1.8cm, footskip=.5cm}}
\\colorlet{{awesome}}{{awesome-red}}
\\setbool{{acvSectionColorHighlight}}{{true}}
{highlight_preamble}
{header["macros"]}
\\begin{{document}}
\\makecvheader[C]
\\makecvfooter
  {{\\today}}
  {{{escape_tex(footer_name)}~~~·~~~Resume}}
  {{\\thepage}}
{body}
\\end{{document}}
"""


def _optimizer_sections(optimizer: dict[str, Any] | None) -> dict[str, Any]:
    if not isinstance(optimizer, dict):
        return {}
    if isinstance(optimizer.get("optimized_sections"), dict):
        return optimizer["optimized_sections"]
    nested = optimizer.get("optimizer")
    if isinstance(nested, dict) and isinstance(nested.get("optimized_sections"), dict):
        return nested["optimized_sections"]
    return {}


def _section_order(
    optimizer: dict[str, Any] | None, sections: dict[str, Any]
) -> list[str]:
    raw = []
    if isinstance(optimizer, dict):
        raw = optimizer.get("section_order") or []
        if not raw and isinstance(optimizer.get("optimizer"), dict):
            raw = optimizer["optimizer"].get("section_order") or []
    order: list[str] = []
    seen: set[str] = set()
    for key in list(raw) + list(_DEFAULT_SECTION_ORDER) + list(sections):
        if key in seen or key not in _DEFAULT_SECTION_ORDER:
            continue
        seen.add(key)
        order.append(key)
    return order


def _header_macros(
    resume_text: str,
    analyzer: dict[str, Any] | None,
    intent: dict[str, Any] | None,
    contact: dict[str, Any] | None,
) -> dict[str, str]:
    info = _resolve_contact(resume_text, analyzer, contact)
    first_name = info["first_name"]
    last_name = info["last_name"]
    lines = [
        f"\\name{{{escape_tex(first_name)}}}{{{escape_tex(last_name)}}}",
    ]
    role = ""
    if isinstance(intent, dict):
        role = str(intent.get("target_role") or "").strip()
    if role:
        lines.append(f"\\position{{{escape_tex(role)}}}")
    if info.get("location"):
        lines.append(f"\\address{{{escape_tex(info['location'])}}}")
    if info.get("phone"):
        lines.append(f"\\mobile{{{escape_tex(info['phone'])}}}")
    if info.get("email"):
        lines.append(f"\\email{{{escape_tex(info['email'])}}}")
    if info.get("homepage"):
        lines.append(f"\\homepage{{{escape_tex(info['homepage'])}}}")
    if info.get("github"):
        lines.append(f"\\github{{{escape_tex(info['github'])}}}")
    if info.get("linkedin"):
        lines.append(f"\\linkedin{{{escape_tex(info['linkedin'])}}}")
    # Awesome-CV always ends the social row with \\[...]. An empty row
    # raises "There's no line here to end" at \makecvheader.
    has_social = any(
        info.get(key) for key in ("phone", "email", "homepage", "github", "linkedin")
    )
    if not has_social:
        lines.append(r"\extrainfo{~}")
    return {
        "macros": "\n".join(lines),
        "first_name": first_name,
        "last_name": last_name,
    }


def _resolve_contact(
    resume_text: str,
    analyzer: dict[str, Any] | None,
    contact: dict[str, Any] | None,
) -> dict[str, str]:
    analyzer = analyzer if isinstance(analyzer, dict) else {}
    contact = contact if isinstance(contact, dict) else {}
    extracted = extract_contact_info(resume_text or "")
    links = analyzer.get("professional_links")
    if not isinstance(links, dict):
        links = extract_professional_links(resume_text or "")

    emails = _string_list(contact.get("emails") or analyzer.get("emails") or extracted.get("emails"))
    if contact.get("email"):
        emails = [str(contact["email"])] + emails
    phones = [
        phone
        for phone in _string_list(
            contact.get("phone_numbers")
            or contact.get("phone")
            or analyzer.get("phone_numbers")
            or extracted.get("phone_numbers")
        )
        if _is_phone(phone)
    ]

    first_name, last_name = _split_name(
        str(contact.get("first_name") or ""),
        str(contact.get("last_name") or ""),
        str(contact.get("name") or ""),
        resume_text or "",
    )
    return {
        "first_name": first_name,
        "last_name": last_name,
        "email": emails[0] if emails else "",
        "phone": phones[0] if phones else "",
        "location": str(contact.get("location") or analyzer.get("location") or ""),
        "github": _account(
            str(contact.get("github") or links.get("github") or ""),
            ("github.com",),
        ),
        "linkedin": _account(
            str(contact.get("linkedin") or links.get("linkedin") or ""),
            ("linkedin.com", "www.linkedin.com"),
        ),
        "homepage": _homepage(contact.get("homepage") or links.get("portfolio")),
    }


def _split_name(
    first_name: str, last_name: str, full_name: str, resume_text: str
) -> tuple[str, str]:
    first_name = first_name.strip()
    last_name = last_name.strip()
    if first_name or last_name:
        return first_name, last_name
    source = full_name.strip() or _guess_name(resume_text)
    parts = source.split()
    if not parts:
        return "Candidate", ""
    if len(parts) == 1:
        return parts[0], ""
    return parts[0], " ".join(parts[1:])


def _guess_name(resume_text: str) -> str:
    for raw in (resume_text or "").splitlines()[:12]:
        line = re.sub(r"\s+", " ", raw).strip(" |-")
        if not line or "@" in line or "http" in line.lower():
            continue
        if _HEADING_LINE.match(line) or any(ch.isdigit() for ch in line):
            continue
        words = _NAME_WORDS.findall(line)
        if 2 <= len(words) <= 5 and len(line) <= 60:
            return " ".join(words)
    return ""


def _account(value: str, hosts: tuple[str, ...]) -> str:
    text = (value or "").strip()
    if not text:
        return ""
    parsed = urlparse(text if "://" in text else f"https://{text}")
    path = parsed.path.strip("/")
    host = (parsed.netloc or "").lower()
    if any(host.endswith(item) for item in hosts) or any(
        text.lower().startswith(item) for item in hosts
    ):
        if "linkedin" in host or "linkedin" in text.lower():
            parts = path.split("/")
            if parts and parts[0] in {"in", "pub", "company"}:
                return parts[1] if len(parts) > 1 else ""
        return path.split("/")[0].split("?")[0]
    if "/" not in text and " " not in text:
        return text.lstrip("@")
    return path.split("/")[0] if path else text.lstrip("@")


def _homepage(value: Any) -> str:
    text = str(value or "").strip()
    if not text:
        return ""
    return re.sub(r"^https?://", "", text, flags=re.I).rstrip("/")


def _is_phone(value: str) -> bool:
    digits = re.sub(r"\D", "", value or "")
    return 10 <= len(digits) <= 15


def _string_list(value: Any) -> list[str]:
    if isinstance(value, str) and value.strip():
        return [value.strip()]
    if isinstance(value, list):
        return [str(item).strip() for item in value if str(item).strip()]
    return []


def _render_section(
    key: str, sections: dict[str, Any], diff: dict[str, Any] | None
) -> str:
    if key == "summary":
        return _render_summary(sections.get("summary"), diff)
    if key == "skills":
        return _render_skills(sections.get("skills"))
    if key == "experience":
        return _render_entries(
            "Experience",
            sections.get("experience"),
            title_key="title",
            org_key="company",
            description_key="description",
            diff_entries=(diff or {}).get("experience") if diff else None,
            id_keys=("company", "title"),
        )
    if key == "projects":
        return _render_entries(
            "Projects",
            sections.get("projects"),
            title_key="role",
            org_key="project_title",
            description_key="project_description",
            diff_entries=(diff or {}).get("projects") if diff else None,
            id_keys=("project_title", "role"),
        )
    if key == "education":
        return _render_entries(
            "Education",
            sections.get("education"),
            title_key="degree",
            org_key="school",
            description_key="description",
            diff_entries=(diff or {}).get("education") if diff else None,
            id_keys=("school", "degree"),
        )
    if key == "other":
        return _render_other(sections.get("other"), diff)
    return ""


def _render_summary(summary: Any, diff: dict[str, Any] | None) -> str:
    text = summary.strip() if isinstance(summary, str) else ""
    if not text:
        return ""
    highlighted = bool(diff and diff.get("summary"))
    # Blank lines + \par match Awesome-CV examples so the body is not
    # pulled onto the "Summary" heading line. Sentence-level \highLight
    # keeps lua-ul from boxing the whole paragraph.
    return (
        "\\cvsection{Summary}\n"
        "\\par\n"
        "\\begin{cvparagraph}\n"
        "\n"
        f"{_maybe_highlight_paragraph(text, highlighted)}\n"
        "\\end{cvparagraph}\n"
    )


def _render_skills(skills: Any) -> str:
    if not isinstance(skills, list) or not skills:
        return ""
    rows: list[str] = []
    for item in skills:
        if not isinstance(item, dict):
            continue
        category = str(item.get("category") or "").strip()
        values = [
            str(skill).strip()
            for skill in (item.get("skills") or [])
            if str(skill).strip()
        ]
        if not category or not values:
            continue
        rows.append(
            f"  \\cvskill{{{escape_tex(category)}}}{{{escape_tex(', '.join(values))}}}"
        )
    if not rows:
        return ""
    return (
        "\\cvsection{Skills}\n"
        "\\begin{cvskills}\n"
        + "\n".join(rows)
        + "\n\\end{cvskills}\n"
    )


def _render_entries(
    title: str,
    entries: Any,
    *,
    title_key: str,
    org_key: str,
    description_key: str,
    diff_entries: list[dict[str, Any]] | None,
    id_keys: tuple[str, ...],
) -> str:
    if not isinstance(entries, list) or not entries:
        return ""
    changed = _changed_bullet_keys(diff_entries, id_keys)
    blocks: list[str] = []
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        rendered = _cventry(
            position=str(entry.get(title_key) or ""),
            organization=str(entry.get(org_key) or ""),
            location=str(entry.get("location") or ""),
            dates=_date_range(entry.get("start_date"), entry.get("end_date")),
            bullets=_bullets(entry.get(description_key)),
            extra=entry.get("additional_info"),
            highlight_keys=changed.get(_identity(entry, id_keys), set()),
        )
        if rendered:
            blocks.append(rendered)
    if not blocks:
        return ""
    return (
        f"\\cvsection{{{title}}}\n"
        "\\begin{cventries}\n"
        + "\n".join(blocks)
        + "\\end{cventries}\n"
    )


def _render_other(other: Any, diff: dict[str, Any] | None) -> str:
    parts: list[str] = []
    diff_entries = (diff or {}).get("other") if diff else None
    for category, items in _iter_other_blocks(other):
        if items and isinstance(items[0], str):
            honors = [
                f"  \\cvhonor{{{escape_tex(item)}}}{{}}{{}}{{}}"
                for item in items
                if str(item).strip()
            ]
            if honors:
                parts.append(
                    f"\\cvsection{{{escape_tex(category)}}}\n"
                    "\\begin{cvhonors}\n"
                    + "\n".join(honors)
                    + "\n\\end{cvhonors}\n"
                )
            continue
        changed = _changed_bullet_keys(
            [
                entry
                for entry in (diff_entries or [])
                if not str(entry.get("category") or "")
                or str(entry.get("category")).lower() == category.lower()
            ],
            ("company", "title"),
        )
        blocks: list[str] = []
        for item in items:
            if not isinstance(item, dict):
                continue
            rendered = _cventry(
                position=str(item.get("title") or ""),
                organization=str(item.get("company") or ""),
                location=str(item.get("location") or ""),
                dates=_date_range(item.get("start_date"), item.get("end_date")),
                bullets=_bullets(item.get("description")),
                extra=item.get("additional_info"),
                highlight_keys=changed.get(_identity(item, ("company", "title")), set()),
            )
            if rendered:
                blocks.append(rendered)
        if blocks:
            parts.append(
                f"\\cvsection{{{escape_tex(category)}}}\n"
                "\\begin{cventries}\n"
                + "\n".join(blocks)
                + "\\end{cventries}\n"
            )
    return "\n".join(parts)


def _iter_other_blocks(other: Any) -> list[tuple[str, list[Any]]]:
    if not isinstance(other, list):
        return []
    blocks: list[tuple[str, list[Any]]] = []
    for block in other:
        if not isinstance(block, dict):
            continue
        if "items" in block or "category" in block:
            category = str(block.get("category") or "Other").strip() or "Other"
            items = block.get("items")
            blocks.append((category, items if isinstance(items, list) else []))
        elif any(key in block for key in ("company", "title", "description")):
            blocks.append(("Other", [block]))
    return blocks


def _cventry(
    *,
    position: str,
    organization: str,
    location: str,
    dates: str,
    bullets: list[tuple[str, str]],
    extra: Any,
    highlight_keys: set[str],
) -> str:
    if not (position or organization or bullets):
        return ""
    extra_text = extra if isinstance(extra, str) else ""
    if extra_text.strip() and extra_text.strip() not in {item for _, item in bullets}:
        bullets = [*bullets, ("extra", extra_text.strip())]
    if bullets:
        items = "\n".join(
            f"        \\item {{{_maybe_highlight(text, key in highlight_keys)}}}"
            for key, text in bullets
        )
        description = (
            "{\n      \\begin{cvitems}\n"
            f"{items}\n"
            "      \\end{cvitems}\n    }"
        )
    else:
        description = "{}"
    return (
        "  \\cventry\n"
        f"    {{{escape_tex(position)}}}\n"
        f"    {{{escape_tex(organization)}}}\n"
        f"    {{{escape_tex(location)}}}\n"
        f"    {{{dates}}}\n"
        f"    {description}\n"
    )


def _bullets(description: Any) -> list[tuple[str, str]]:
    if isinstance(description, dict):
        def _sort_key(key: Any) -> tuple[int, str]:
            raw = str(key)
            return (int(raw), raw) if raw.isdigit() else (10**9, raw)

        return [
            (str(key), str(description[key]).strip())
            for key in sorted(description, key=_sort_key)
            if str(description[key] or "").strip()
        ]
    if isinstance(description, list):
        return [
            (str(index + 1), str(item).strip())
            for index, item in enumerate(description)
            if str(item).strip()
        ]
    if isinstance(description, str) and description.strip():
        return [("1", description.strip())]
    return []


def _changed_bullet_keys(
    entries: list[dict[str, Any]] | None, id_keys: tuple[str, ...]
) -> dict[str, set[str]]:
    changed: dict[str, set[str]] = {}
    for entry in entries or []:
        if not isinstance(entry, dict):
            continue
        identity = _identity(entry, id_keys)
        keys = {
            str(bullet.get("key"))
            for bullet in (entry.get("bullets") or [])
            if isinstance(bullet, dict) and bullet.get("key") is not None
        }
        if identity and keys:
            changed.setdefault(identity, set()).update(keys)
    return changed


def _identity(entry: dict[str, Any], id_keys: tuple[str, ...]) -> str:
    return " ".join(str(entry.get(key) or "").strip().lower() for key in id_keys)


def _date_range(start: Any, end: Any) -> str:
    start_text = escape_tex(str(start or "").strip())
    end_text = escape_tex(str(end or "").strip())
    if start_text and end_text:
        return f"{start_text} -- {end_text}"
    return start_text or end_text


def _maybe_highlight(text: str, highlighted: bool) -> str:
    escaped = escape_tex(text)
    if highlighted and escaped:
        return r"\highLight{" + escaped + "}"
    return escaped


_SENTENCE_SPLIT = re.compile(r"(?<=[.!?])\s+")


def _maybe_highlight_paragraph(text: str, highlighted: bool) -> str:
    """Highlight a paragraph without wrapping it in one \\highLight{...}."""
    if not highlighted:
        return escape_tex(text)
    parts = [part.strip() for part in _SENTENCE_SPLIT.split(text.strip()) if part.strip()]
    if not parts:
        return escape_tex(text)
    return " ".join(_maybe_highlight(part, True) for part in parts)
